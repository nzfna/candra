#!/usr/bin/env node
// Generates every published artifact from the canonical source in content/source:
//   packages/id/messages/<ns>.json      ICU flavor (next-intl, @candra/core)
//   packages/id/i18next/<ns>.json       i18next flavor ({{name}} placeholders)
//   packages/id/src/generated/*.ts      typed `as const` objects for type-safe keys
// With --init-meta it also creates review-status files (all keys start as `draft`).
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { ROOT, META_DIR, loadSource, flatten, loadMeta } from '../lib.mjs';

const PKG = path.join(ROOT, 'packages', 'id');
const toI18next = (s) => s.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, '{{$1}}');
const mapStrings = (tree, fn) =>
  Object.fromEntries(
    Object.entries(tree).map(([k, v]) => [k, typeof v === 'string' ? fn(v) : mapStrings(v, fn)]),
  );
const json = (o) => JSON.stringify(o, null, 2) + '\n';
const HEADER = '// AUTO-GENERATED by tools/build-pack. Edit content/source/*.json instead.\n';

const source = await loadSource();
const namespaces = Object.keys(source).sort();

if (process.argv.includes('--init-meta')) {
  await mkdir(META_DIR, { recursive: true });
  for (const ns of namespaces) {
    const existing = (await loadMeta(ns)) ?? {};
    const next = {};
    for (const [key] of flatten(source[ns])) next[key] = existing[key] ?? 'draft';
    await writeFile(path.join(META_DIR, `${ns}.json`), json(next));
  }
  console.log(`meta: initialised ${namespaces.length} namespaces`);
  process.exit(0);
}

await mkdir(path.join(PKG, 'messages'), { recursive: true });
await mkdir(path.join(PKG, 'i18next'), { recursive: true });
await mkdir(path.join(PKG, 'src', 'generated'), { recursive: true });

const i18next = {};
for (const ns of namespaces) {
  await writeFile(path.join(PKG, 'messages', `${ns}.json`), json(source[ns]));
  i18next[ns] = mapStrings(source[ns], toI18next);
  await writeFile(path.join(PKG, 'i18next', `${ns}.json`), json(i18next[ns]));
}

const nsConsts = namespaces.map((ns) => `export const ${ns} = ${JSON.stringify(source[ns], null, 2)} as const;\n`);
await writeFile(
  path.join(PKG, 'src', 'generated', 'messages.ts'),
  HEADER +
    nsConsts.join('\n') +
    `\nexport const messages = { ${namespaces.join(', ')} } as const;\n` +
    `export type IdMessages = typeof messages;\n` +
    `export const namespaces = ${JSON.stringify(namespaces)} as const;\n`,
);
await writeFile(
  path.join(PKG, 'src', 'generated', 'i18next.ts'),
  HEADER +
    `export const resources = { id: ${JSON.stringify(i18next, null, 2)} } as const;\n` +
    `export const namespaces = ${JSON.stringify(namespaces)} as const;\n` +
    `export const defaultNS = 'common' as const;\n`,
);
const total = namespaces.reduce((n, ns) => n + flatten(source[ns]).length, 0);
console.log(`build-pack: ${namespaces.length} namespaces, ${total} keys`);
